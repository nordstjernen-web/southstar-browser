pub fn script_properties(script: Script) -> ScriptProperties {
    usize::try_from(script.0)
        .ok()
        .and_then(|index| SCRIPT_PROPERTIES.get(index))
        .copied()
        .unwrap_or(SCRIPT_PROPERTIES[0])
}

pub fn gravity_to_rotation(gravity: Gravity) -> f64 {
    match gravity {
        Gravity::Auto | Gravity::South => 0.0,
        Gravity::North => core::f64::consts::PI,
        Gravity::East => -core::f64::consts::FRAC_PI_2,
        Gravity::West => core::f64::consts::FRAC_PI_2,
    }
}

pub fn gravity_get_for_matrix(matrix: Option<&Matrix>) -> Gravity {
    let Some(matrix) = matrix else {
        return Gravity::South;
    };
    let x = matrix.xy;
    let y = matrix.yy;
    if x.abs() > y.abs() {
        if x > 0.0 {
            Gravity::West
        } else {
            Gravity::East
        }
    } else if y < 0.0 {
        Gravity::North
    } else {
        Gravity::South
    }
}

pub fn gravity_get_for_script_and_width(
    script: Script,
    wide: bool,
    base_gravity: Gravity,
    hint: GravityHint,
) -> Gravity {
    let props = script_properties(script);
    let base_gravity = if base_gravity == Gravity::Auto {
        props.preferred_gravity
    } else {
        base_gravity
    };

    if !base_gravity.is_vertical() || wide {
        return base_gravity;
    }

    match hint {
        GravityHint::Natural => {
            if props.vert_dir == VerticalDirection::None {
                return Gravity::South;
            }
            if (base_gravity == Gravity::East) ^ (props.vert_dir == VerticalDirection::Btt) {
                Gravity::South
            } else {
                Gravity::North
            }
        }
        GravityHint::Strong => base_gravity,
        GravityHint::Line => {
            if (base_gravity == Gravity::East) ^ (props.horiz_dir == Direction::Rtl) {
                Gravity::South
            } else {
                Gravity::North
            }
        }
    }
}
