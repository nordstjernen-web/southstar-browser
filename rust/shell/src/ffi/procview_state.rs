pub type NotifyFn = Option<
    unsafe extern "C" fn(
        view: *mut NsProcView,
        event: c_int,
        text: *const c_char,
        data: *mut c_void,
    ),
>;

#[repr(C)]
#[derive(Clone, Copy)]
pub union GMutex {
    pub p: *mut c_void,
    pub i: [c_uint; 2],
}

#[repr(C)]
#[derive(Clone, Copy, Default)]
pub struct Wheel {
    pub x: c_int,
    pub y: c_int,
    pub dx: c_int,
    pub dy: c_int,
    pub viewport: c_int,
}

#[repr(C)]
#[derive(Clone, Copy)]
pub struct TilesReq {
    pub tile_h: c_int,
    pub want_y0: c_int,
    pub want_y1: c_int,
    pub gen_: c_int,
    pub vp_held: c_int,
    pub fill: c_int,
    pub have: *const c_char,
    pub hold: *const c_char,
}

#[repr(C)]
