#!/usr/bin/env python3
"""Generate rust/psl/src/table.rs from the Public Suffix List.

Usage: gen-psl-table.py [PUBLIC_SUFFIX_LIST] [OUT]

PUBLIC_SUFFIX_LIST defaults to https://publicsuffix.org/list/public_suffix_list.dat,
fetched over the network; pass a local copy to generate offline. Both the ICANN
and the private sections are kept, as libpsl's built-in list did. Every rule is
written in its UTF-8 form and, when it has non-ASCII labels, in its Punycode form
too, so hosts match whichever form they arrive in. The three rule kinds (plain,
wildcard and exception) become sorted arrays the crate binary searches. The output
is run through rustfmt when it is on the PATH.
"""
import os
import shutil
import subprocess
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCE = sys.argv[1] if len(sys.argv) > 1 else \
    'https://publicsuffix.org/list/public_suffix_list.dat'
OUT = sys.argv[2] if len(sys.argv) > 2 else \
    os.path.join(ROOT, 'rust', 'psl', 'src', 'table.rs')


def load(source):
    if source.startswith('http://') or source.startswith('https://'):
        with urllib.request.urlopen(source) as response:
            return response.read().decode('utf-8')
    with open(source, encoding='utf-8') as f:
        return f.read()


def punycode(rule):
    labels = []
    for label in rule.split('.'):
        if label.isascii():
            labels.append(label)
        else:
            labels.append('xn--' + label.encode('punycode').decode('ascii'))
    return '.'.join(labels)


def parse(text):
    version = ''
    plain, wildcard, exception = set(), set(), set()
    for raw in text.splitlines():
        line = raw.strip()
        if line.startswith('// VERSION:'):
            version = line.split(':', 1)[1].strip()
        if not line or line.startswith('//'):
            continue
        rule = line.split()[0].lower()
        if rule.startswith('!'):
            target = exception
            rule = rule[1:]
        elif rule.startswith('*.'):
            target = wildcard
            rule = rule[2:]
        else:
            target = plain
        if '*' in rule:
            sys.exit(f'unsupported rule with an inner wildcard: {line}')
        target.add(rule)
        target.add(punycode(rule))
    return version, sorted(plain), sorted(wildcard), sorted(exception)


def array(name, rules):
    body = ''.join(f'    "{rule}",\n' for rule in rules)
    return f'pub static {name}: [&str; {len(rules)}] = [\n{body}];\n'


def main():
    version, plain, wildcard, exception = parse(load(SOURCE))
    out = (
        '//! Southstar PSL — the Public Suffix List '
        f'{version}, generated by scripts/gen-psl-table.py; regenerate rather than edit.\n'
        '//! Data: Public Suffix List contributors, https://publicsuffix.org\n'
        '//! SPDX-License-Identifier: MPL-2.0\n\n'
        + array('RULES', plain) + '\n'
        + array('WILDCARDS', wildcard) + '\n'
        + array('EXCEPTIONS', exception)
    )
    with open(OUT, 'w', encoding='utf-8', newline='\n') as f:
        f.write(out)
    rustfmt = shutil.which('rustfmt')
    if rustfmt:
        subprocess.run([rustfmt, '--edition', '2024', OUT], check=True)
    print(f'{OUT}: {len(plain)} rules, {len(wildcard)} wildcards, {len(exception)} exceptions')


if __name__ == '__main__':
    main()
