#!/usr/bin/env python3
"""Generate rust/bidi/src/tables.rs from the Unicode Character Database.

Usage: gen-bidi-tables.py UCD_DIR [OUT]

UCD_DIR is one Unicode version laid out as on unicode.org's
Public/<version>/ucd/: UnicodeData.txt, BidiBrackets.txt,
BidiMirroring.txt and extracted/DerivedBidiClass.txt. The tables are the
Bidi_Class of every code point (with the @missing defaults for unassigned
ones), the paired brackets of UAX #9 BD16 keyed to their canonical opening
bracket, and Bidi_Mirroring_Glyph. The output is run through rustfmt when it
is on the PATH.
"""
import os
import re
import shutil
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
UCD = sys.argv[1] if len(sys.argv) > 1 else '/usr/share/unicode'
OUT = sys.argv[2] if len(sys.argv) > 2 else \
    os.path.join(ROOT, 'rust', 'bidi', 'src', 'tables.rs')

MAX = 0x110000

CLASSES = ['L', 'R', 'AL', 'EN', 'ES', 'ET', 'AN', 'CS', 'NSM', 'BN', 'B',
           'S', 'WS', 'ON', 'LRE', 'LRO', 'RLE', 'RLO', 'PDF', 'LRI', 'RLI',
           'FSI', 'PDI']
LONG = {'Left_To_Right': 'L', 'Right_To_Left': 'R', 'Arabic_Letter': 'AL',
        'European_Number': 'EN', 'European_Separator': 'ES',
        'European_Terminator': 'ET', 'Arabic_Number': 'AN',
        'Common_Separator': 'CS', 'Nonspacing_Mark': 'NSM',
        'Boundary_Neutral': 'BN', 'Paragraph_Separator': 'B',
        'Segment_Separator': 'S', 'White_Space': 'WS', 'Other_Neutral': 'ON'}


def ucd_file(*names):
    for name in names:
        path = os.path.join(UCD, name)
        if os.path.exists(path):
            return path
    sys.exit('missing %s under %s' % (names[0], UCD))


def records(path, missing=False):
    for line in open(path, encoding='utf-8'):
        if missing:
            m = re.match(r'#\s*@missing:\s*([0-9A-F.]+)\s*;\s*(\w+)', line)
            if not m:
                continue
            fields = [m.group(1), m.group(2)]
        else:
            line = line.split('#', 1)[0].strip()
            if not line:
                continue
            fields = [x.strip() for x in line.split(';')]
        rng = fields[0]
        if '..' in rng:
            lo, hi = [int(x, 16) for x in rng.split('..')]
        else:
            lo = hi = int(rng, 16)
        yield lo, hi, fields[1:]


def version():
    path = ucd_file('extracted/DerivedBidiClass.txt', 'DerivedBidiClass.txt')
    for line in open(path, encoding='utf-8'):
        m = re.match(r'#\s*DerivedBidiClass-([0-9.]+)\.txt', line)
        if m:
            return m.group(1)
    return 'unknown'


def class_table():
    value = [CLASSES.index('L')] * MAX
    path = ucd_file('extracted/DerivedBidiClass.txt', 'DerivedBidiClass.txt')
    for lo, hi, fields in records(path, missing=True):
        short = LONG.get(fields[0], fields[0])
        for cp in range(lo, hi + 1):
            value[cp] = CLASSES.index(short)
    for lo, hi, fields in records(path):
        for cp in range(lo, hi + 1):
            value[cp] = CLASSES.index(fields[0])
    return value


def canonical_singletons():
    singleton = {}
    for line in open(ucd_file('UnicodeData.txt'), encoding='utf-8'):
        f = line.rstrip('\n').split(';')
        parts = f[5].split()
        if len(parts) == 1 and not parts[0].startswith('<'):
            singleton[int(f[0], 16)] = int(parts[0], 16)
    return singleton


def bracket_table():
    singleton = canonical_singletons()
    canonical = lambda cp: singleton.get(cp, cp)
    out = {}
    for lo, _, fields in records(ucd_file('BidiBrackets.txt')):
        pair = int(fields[0], 16)
        if fields[1] == 'o':
            out[lo] = (canonical(lo), True)
        else:
            out[lo] = (canonical(pair), False)
    return out


def mirror_table():
    out = {}
    for lo, _, fields in records(ucd_file('BidiMirroring.txt')):
        out[lo] = int(fields[0], 16)
    return out


def ranges(values):
    starts, out = [], []
    previous = None
    for cp, v in enumerate(values):
        if v != previous:
            starts.append(cp)
            out.append(v)
            previous = v
    return starts, out


def array(name, kind, items, fmt):
    body = ', '.join(fmt(x) for x in items)
    return 'pub static %s: [%s; %d] = [%s];\n' % (name, kind, len(items),
                                                   body)


def main():
    class_starts, class_values = ranges(class_table())
    brackets = bracket_table()
    bracket_keys = sorted(brackets)
    mirrors = mirror_table()
    mirror_keys = sorted(mirrors)
    hexa = lambda x: '0x%x' % x
    out = []
    out.append('//! Southstar — the Unicode %s bidi tables (Bidi_Class, '
               'paired brackets and mirrored glyphs), generated by '
               'scripts/gen-bidi-tables.py.\n' % version())
    out.append('//! Copyright 2026 Andreas Røsdal\n')
    out.append('//! SPDX-License-Identifier: LicenseRef-NSL-1.0 OR '
               'GPL-3.0-or-later\n\n')
    out.append(array('CLASS_STARTS', 'u32', class_starts, hexa))
    out.append(array('CLASS_VALUES', 'u8', class_values, str))
    out.append(array('BRACKET_KEYS', 'u32', bracket_keys, hexa))
    out.append(array('BRACKET_PAIRS', 'u32',
                     [brackets[k][0] | brackets[k][1] << 31
                      for k in bracket_keys], hexa))
    out.append(array('MIRROR_KEYS', 'u32', mirror_keys, hexa))
    out.append(array('MIRROR_VALUES', 'u32',
                     [mirrors[k] for k in mirror_keys], hexa))
    with open(OUT, 'w', encoding='utf-8') as f:
        f.write(''.join(out))
    if shutil.which('rustfmt'):
        subprocess.run(['rustfmt', '--edition', '2024', OUT], check=True)


main()
