import argparse
import base64
import hashlib
import io
import json
import os
import re
import shutil
import subprocess
import sys
import tarfile
import tomllib
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
STAGING = ROOT / "target" / "pdfjs-crate"
CARGO = os.environ.get("CARGO") or shutil.which("cargo") or "cargo"
USER_AGENT = "southstar-update-pdfjs"
CRATE = "southstar-pdfjs"
CRATES_IO_LIMIT = 10 * 1024 * 1024
KEEP = [
    (r"LICENSE", "LICENSE"),
    (r"legacy/build/(pdf\.min\.mjs|pdf\.worker\.min\.mjs)", r"build/\1"),
    (r"cmaps/([^/]+)", r"cmaps/\1"),
    (r"standard_fonts/([^/]+)", r"standard_fonts/\1"),
    (r"wasm/((?:openjpeg|jbig2|qcms_bg)\.wasm|LICENSE_[A-Z0-9_]+)", r"wasm/\1"),
    (r"iccs/([^/]+)", r"iccs/\1"),
]

MANIFEST = """\
[package]
name = "southstar-pdfjs"
version = "{version}"
edition = "2024"
rust-version = "1.85"
description = "Mozilla's pdf.js {version} (pdfjs-dist, legacy build) with its CMaps, standard fonts and WebAssembly decoders, embedded for Southstar's PDF viewer"
readme = "README.md"
license = "Apache-2.0"
repository = "{repository}"
homepage = "{homepage}"
keywords = ["pdf", "pdfjs", "southstar"]
categories = ["rendering"]
include = [
    "Cargo.toml",
    "README.md",
    "LICENSE",
    "src/**",
    "build/**",
    "cmaps/**",
    "standard_fonts/**",
    "wasm/**",
    "iccs/**",
]

[lib]
path = "src/lib.rs"

[package.metadata.southstar]
upstream-version = "{version}"
upstream-integrity = "{integrity}"

[workspace]
"""

LIB_RS = """\
//! Southstar — the pdf.js files of the pdfjs-dist package by their path in it, with their media types.
//!
//! Copyright 2026 Andreas Røsdal
//! SPDX-License-Identifier: Apache-2.0

#![forbid(unsafe_code)]

mod files;

pub const VERSION: &str = "{version}";

pub struct File {{
    pub bytes: &'static [u8],
    pub content_type: &'static str,
}}

fn content_type(path: &str) -> &'static str {{
    let extension = path.rsplit_once('.').map_or("", |(_, extension)| extension);
    match extension {{
        "mjs" | "js" => "text/javascript; charset=utf-8",
        "wasm" => "application/wasm",
        "ttf" => "font/ttf",
        "icc" => "application/vnd.iccprofile",
        _ => "application/octet-stream",
    }}
}}

pub fn file(path: &str) -> Option<File> {{
    files::FILES
        .iter()
        .find(|(name, _)| *name == path)
        .map(|&(name, bytes)| File {{
            bytes,
            content_type: content_type(name),
        }})
}}
"""

README = """\
# southstar-pdfjs

Mozilla's [pdf.js](https://github.com/mozilla/pdf.js) {version}, embedded for
the PDF viewer of the [Southstar]({homepage}) browser. The crate holds files
from the prebuilt npm package pdfjs-dist {version}, unmodified, and looks them
up by their path in the package:

- `build/pdf.min.mjs` and `build/pdf.worker.min.mjs` — the library and its
  worker, from the package's `legacy/build` (the build that avoids the newest
  JavaScript and web platform features);
- `cmaps/` — the CMaps for CJK and other CID-keyed fonts;
- `standard_fonts/` — the standard 14 font substitutes (Foxit and Liberation);
- `wasm/` — the OpenJPEG, JBIG2 and QCMS WebAssembly decoders;
- `iccs/` — the CMYK ICC profile;
- `LICENSE` — pdf.js's Apache License 2.0. The fonts, decoders and profile
  carry their own licence files next to them.

```rust
let worker = southstar_pdfjs::file("build/pdf.worker.min.mjs").unwrap();
assert_eq!(worker.content_type, "text/javascript; charset=utf-8");
assert_eq!(southstar_pdfjs::VERSION, "{version}");
```

Not taken from the package: the modern `build/`, source maps, type
declarations, the scripting sandbox and its QuickJS build, the image decoders'
non-WebAssembly fallbacks and the `web/` viewer components.

The crate's version is the pdf.js version. It is generated, never edited, by
`scripts/update-pdfjs.py` in the Southstar repository, which checks the npm
tarball against the registry's integrity hash ({integrity}).
"""


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request) as response:
        return response.read()


def target_of(name):
    for pattern, replacement in KEEP:
        if re.fullmatch(pattern, name):
            return re.sub(pattern, replacement, name)
    return None


def files_rs(paths):
    lines = [
        "//! Southstar — the pdf.js files this crate embeds, generated by scripts/update-pdfjs.py.",
        "",
        "#[rustfmt::skip]",
        "pub(crate) const FILES: &[(&str, &[u8])] = &[",
    ]
    for path in paths:
        lines.append(f'    ("{path}", include_bytes!("../{path}")),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def write(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8", newline="\n")


def generate(version, out):
    meta = json.loads(fetch(f"https://registry.npmjs.org/pdfjs-dist/{version}"))
    tarball = fetch(meta["dist"]["tarball"])
    integrity = meta["dist"]["integrity"]
    algorithm, digest = integrity.split("-", 1)
    if hashlib.new(algorithm, tarball).digest() != base64.b64decode(digest):
        sys.exit("update-pdfjs: the tarball does not match the registry's integrity hash")
    shutil.rmtree(out, ignore_errors=True)
    out.mkdir(parents=True)
    written = []
    with tarfile.open(fileobj=io.BytesIO(tarball), mode="r:gz") as archive:
        for member in archive.getmembers():
            if not member.isfile() or not member.name.startswith("package/"):
                continue
            target = target_of(member.name.removeprefix("package/"))
            if target is None:
                continue
            destination = out / target
            destination.parent.mkdir(parents=True, exist_ok=True)
            destination.write_bytes(archive.extractfile(member).read())
            written.append(target)
    workspace = tomllib.loads((ROOT / "Cargo.toml").read_text(encoding="utf-8"))["workspace"]["package"]
    fields = {"version": version, "integrity": integrity,
              "repository": workspace["repository"], "homepage": workspace["homepage"]}
    served = sorted(p for p in written if "LICENSE" not in p)
    write(out / "Cargo.toml", MANIFEST.format(**fields))
    write(out / "README.md", README.format(**fields))
    write(out / "src" / "lib.rs", LIB_RS.format(**fields))
    write(out / "src" / "files.rs", files_rs(served))
    print(f"update-pdfjs: generated {CRATE} {version} in {out}, {len(served)} files")


def cargo(out, *args):
    command = [CARGO, *args, "--manifest-path", str(out / "Cargo.toml"), "--target-dir", str(out / "target")]
    print("update-pdfjs: " + " ".join(command), flush=True)
    subprocess.run(command, cwd=out, check=True)


def staged_version(out):
    manifest = out / "Cargo.toml"
    if not manifest.is_file():
        sys.exit(f"update-pdfjs: no generated crate in {out}; run `update-pdfjs.py generate VERSION` first")
    return tomllib.loads(manifest.read_text(encoding="utf-8"))["package"]["version"]


def check(out):
    version = staged_version(out)
    cargo(out, "package", "--allow-dirty")
    packaged = out / "target" / "package" / f"{CRATE}-{version}.crate"
    size = packaged.stat().st_size
    print(f"update-pdfjs: {packaged} is {size} bytes ({size / 1048576:.2f} MiB)")
    if size >= CRATES_IO_LIMIT:
        sys.exit("update-pdfjs: the packaged crate is over crates.io's 10 MB limit")
    cargo(out, "publish", "--dry-run", "--allow-dirty", "--no-verify")


def publish(out):
    staged_version(out)
    cargo(out, "publish", "--allow-dirty")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--out", type=Path, default=STAGING, help="the staging directory (default target/pdfjs-crate)")
    commands = parser.add_subparsers(dest="command", required=True)
    generate_parser = commands.add_parser("generate", help="build the crate from a pdfjs-dist release")
    generate_parser.add_argument("version", help="the pdfjs-dist version, e.g. 6.4.299")
    commands.add_parser("check", help="cargo package it, check its size and run cargo publish --dry-run")
    commands.add_parser("publish", help="publish the generated crate to crates.io")
    args = parser.parse_args()
    out = args.out.resolve()
    if ROOT / "third_party" in [out, *out.parents]:
        sys.exit("update-pdfjs: the crate is staged outside third_party/")
    if args.command == "generate":
        generate(args.version, out)
    elif args.command == "check":
        check(out)
    else:
        publish(out)


if __name__ == "__main__":
    main()
