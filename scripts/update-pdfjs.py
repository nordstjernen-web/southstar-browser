import argparse
import base64
import hashlib
import io
import json
import re
import shutil
import sys
import tarfile
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DEST = ROOT / "third_party" / "pdfjs"
USER_AGENT = "southstar-update-pdfjs"
KEEP = [
    (r"LICENSE", "LICENSE"),
    (r"legacy/build/(pdf\.min\.mjs|pdf\.worker\.min\.mjs)", r"build/\1"),
    (r"cmaps/([^/]+)", r"cmaps/\1"),
    (r"standard_fonts/([^/]+)", r"standard_fonts/\1"),
    (r"wasm/((?:openjpeg|jbig2|qcms_bg)\.wasm|LICENSE_[A-Z0-9_]+)", r"wasm/\1"),
    (r"iccs/([^/]+)", r"iccs/\1"),
]
VENDORED_DIRS = ["build", "cmaps", "standard_fonts", "wasm", "iccs"]


def fetch(url):
    request = urllib.request.Request(url, headers={"User-Agent": USER_AGENT})
    with urllib.request.urlopen(request) as response:
        return response.read()


def target_of(name):
    for pattern, replacement in KEEP:
        if re.fullmatch(pattern, name):
            return re.sub(pattern, replacement, name)
    return None


def files_rs(paths):
    lines = [
        "//! Southstar — the vendored pdf.js files, generated by scripts/update-pdfjs.py.",
        "",
        "#[rustfmt::skip]",
        "pub(crate) const FILES: &[(&str, &[u8])] = &[",
    ]
    for path in paths:
        lines.append(f'    ("{path}", include_bytes!("../{path}")),')
    lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("version", help="the pdfjs-dist version, e.g. 6.4.299")
    args = parser.parse_args()
    meta = json.loads(fetch(f"https://registry.npmjs.org/pdfjs-dist/{args.version}"))
    tarball = fetch(meta["dist"]["tarball"])
    algorithm, digest = meta["dist"]["integrity"].split("-", 1)
    if hashlib.new(algorithm, tarball).digest() != base64.b64decode(digest):
        sys.exit("update-pdfjs: the tarball does not match the registry's integrity hash")
    for directory in VENDORED_DIRS:
        shutil.rmtree(DEST / directory, ignore_errors=True)
    written = []
    with tarfile.open(fileobj=io.BytesIO(tarball), mode="r:gz") as archive:
        for member in archive.getmembers():
            if not member.isfile() or not member.name.startswith("package/"):
                continue
            target = target_of(member.name.removeprefix("package/"))
            if target is None:
                continue
            out = DEST / target
            out.parent.mkdir(parents=True, exist_ok=True)
            out.write_bytes(archive.extractfile(member).read())
            written.append(target)
    served = sorted(p for p in written if "LICENSE" not in p)
    (DEST / "src" / "files.rs").write_text(files_rs(served), encoding="utf-8", newline="\n")
    stamps = [
        ("README.md", r"pdfjs-dist [0-9][0-9.]*[0-9]", f"pdfjs-dist {args.version}"),
        ("Cargo.toml", r'upstream-version = "[^"]*"', f'upstream-version = "{args.version}"'),
        ("src/lib.rs", r'VERSION: &str = "[^"]*"', f'VERSION: &str = "{args.version}"'),
    ]
    for name, pattern, replacement in stamps:
        path = DEST / name
        text = path.read_text(encoding="utf-8")
        path.write_text(re.sub(pattern, replacement, text), encoding="utf-8", newline="\n")
    print(f"update-pdfjs: vendored pdfjs-dist {args.version}, {len(served)} files")


if __name__ == "__main__":
    main()
